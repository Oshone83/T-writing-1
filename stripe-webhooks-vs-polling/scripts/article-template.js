// scripts/article-template.js — (re)writes ARTICLE-RESULTS.md: the article-values page rendered for an
// empty database, so every value is [PENDING: …]. A test checks the committed file matches this output.
//
//   node scripts/article-template.js
import fs from 'node:fs';
import path from 'node:path';
import { isMain, PROJECT_DIR } from '../lib/env.js';
import { openDb } from '../lib/db.js';
import { analyze } from '../analyze.js';
import { renderArticleValues } from '../lib/article.js';

export function articleTemplate() {
  const header = `<!-- Generated by scripts/article-template.js. Do not edit: after the real run, ./exp analyze
     writes the same page with measured values to results/article-values.md. -->

> **No real Stripe measurements yet.** Every value below is [PENDING]. After the live test-mode run,
> \`./exp analyze\` fills them in at **results/article-values.md**. Simulated numbers from the demo
> live only in demo-results/ and must never be copied here.

`;
  return header + renderArticleValues(analyze(openDb(':memory:')), {});
}

if (isMain(import.meta.url)) {
  fs.writeFileSync(path.join(PROJECT_DIR, 'ARTICLE-RESULTS.md'), articleTemplate());
  console.log('wrote ARTICLE-RESULTS.md');
}
